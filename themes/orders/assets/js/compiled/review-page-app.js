		async function submitReview() {
			if (!get(rating) || !get(recensione).trim() || !get(ordine).trim()) {
				set(messaggio, traduzioni[get(lingua)].errorMessage);
				return;
			}

			if (parseInt(get(rating)) <= 3 && !get(showSecondFeedbackPrompt)) {
				set(showSecondFeedbackPrompt, true);
				return;
			}

			set(isLoading, true);

			await fetch("https://kettleblaze-store-server.fly.dev/save-discord-review", {
				method: "POST",
				headers: { "Content-Type": "application/json" },
				body: JSON.stringify({
					name: get(nome),
					email: get(email),
					rating: get(rating),
					review: get(recensione),
					orderId: get(ordine)
				})
			}).then((r) => {
				if (r.ok) {
					set(complete, true);
					set(isLoading, false);
					set(nome, "");
					set(email, "");
					set(rating, "5");
					set(recensione, "");
					set(ordine, "");
				} else {
					set(complete, false);
					set(isLoading, false);
					set(messaggio, traduzioni[get(lingua)].errorMessage);
				}
			}).catch((e) => {
				set(complete, false);
				set(isLoading, false);
				set(messaggio, traduzioni[get(lingua)].errorMessage);
			});
		}

